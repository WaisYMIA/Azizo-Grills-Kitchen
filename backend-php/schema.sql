-- Azizo Butchery & Grill — MySQL schema.
-- Run automatically on every request (see db.php) — importing it by hand via
-- phpMyAdmin first is optional, not required.

CREATE TABLE IF NOT EXISTS customers (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  phone VARCHAR(32) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS products (
  id VARCHAR(64) PRIMARY KEY,
  category_group VARCHAR(64) NOT NULL,
  cat VARCHAR(64) NOT NULL,
  kind VARCHAR(64) NULL,
  name VARCHAR(255) NOT NULL,
  description TEXT NULL,
  price INT NOT NULL,
  unit VARCHAR(32) NOT NULL,
  img VARCHAR(512) NULL,
  badges VARCHAR(512) NULL,
  origin VARCHAR(255) NULL,
  in_stock TINYINT(1) NOT NULL DEFAULT 1,
  cost_price INT NOT NULL DEFAULT 0,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS orders (
  id INT AUTO_INCREMENT PRIMARY KEY,
  customer_id INT NULL,
  customer_name VARCHAR(255) NULL,
  customer_phone VARCHAR(32) NOT NULL,
  fulfilment VARCHAR(32) NOT NULL,
  branch VARCHAR(128) NULL,
  pickup_time VARCHAR(64) NULL,
  notes VARCHAR(300) NULL,
  area VARCHAR(80) NULL,
  recurring VARCHAR(16) NULL,
  delivery_address VARCHAR(512) NULL,
  delivery_lat DOUBLE NULL,
  delivery_lng DOUBLE NULL,
  delivery_fee INT NOT NULL DEFAULT 0,
  payment_method VARCHAR(32) NOT NULL,
  mpesa_receipt VARCHAR(64) NULL,
  promo_code VARCHAR(64) NULL,
  items_subtotal INT NOT NULL,
  total INT NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'received',
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS order_items (
  id INT AUTO_INCREMENT PRIMARY KEY,
  order_id INT NOT NULL,
  product_id VARCHAR(64) NULL,
  name VARCHAR(255) NOT NULL,
  qty INT NOT NULL,
  unit VARCHAR(32) NULL,
  unit_price INT NOT NULL,
  line_total INT NOT NULL,
  cost_price INT NOT NULL DEFAULT 0,
  FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS mpesa_transactions (
  id INT AUTO_INCREMENT PRIMARY KEY,
  order_id INT NULL,
  checkout_request_id VARCHAR(128) NULL,
  phone VARCHAR(32) NULL,
  amount INT NULL,
  status VARCHAR(32) DEFAULT 'pending',
  mpesa_receipt VARCHAR(64) NULL,
  raw_callback TEXT NULL,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS branches (
  id VARCHAR(40) PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  area VARCHAR(60) NULL,
  address VARCHAR(160) NULL,
  `query` VARCHAR(200) NULL,
  lat DOUBLE NULL,
  lng DOUBLE NULL,
  phone VARCHAR(24) NOT NULL DEFAULT '',
  hours VARCHAR(60) NOT NULL DEFAULT 'Open 24 hours',
  is_main TINYINT(1) NOT NULL DEFAULT 0,
  listed TINYINT(1) NOT NULL DEFAULT 1,
  sort_order INT NOT NULL DEFAULT 0,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Reporting (v1.2): business expenses and a status history used for "time to complete" figures.
CREATE TABLE IF NOT EXISTS expenses (
  id INT AUTO_INCREMENT PRIMARY KEY,
  expense_date DATE NOT NULL,
  category VARCHAR(64) NOT NULL,
  description VARCHAR(255) NULL,
  amount INT NOT NULL,
  branch VARCHAR(128) NULL,
  paid_via VARCHAR(40) NULL,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_expenses_date (expense_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS order_status_log (
  id INT AUTO_INCREMENT PRIMARY KEY,
  order_id INT NOT NULL,
  status VARCHAR(32) NOT NULL,
  changed_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_statuslog_order (order_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Delivery areas (v1.7): every Nairobi region split into zones; admin ticks the ones served.
CREATE TABLE IF NOT EXISTS areas (
  id VARCHAR(50) PRIMARY KEY,
  region VARCHAR(80) NOT NULL,
  name VARCHAR(80) NOT NULL,
  corridor VARCHAR(60) NOT NULL DEFAULT '',
  lat DOUBLE NOT NULL,
  lng DOUBLE NOT NULL,
  active TINYINT(1) NOT NULL DEFAULT 0,
  sort_order INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS area_settings (
  skey VARCHAR(40) PRIMARY KEY,
  svalue TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- v1.8: per-branch stock (only what is OUT at a branch is stored) and verified reviews.
CREATE TABLE IF NOT EXISTS branch_stock_out (
  branch_id VARCHAR(40) NOT NULL,
  product_id VARCHAR(64) NOT NULL,
  PRIMARY KEY (branch_id, product_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS reviews (
  id INT AUTO_INCREMENT PRIMARY KEY,
  order_id INT NOT NULL UNIQUE,
  name VARCHAR(80) NULL,
  rating TINYINT NOT NULL,
  comment VARCHAR(700) NULL,
  photo VARCHAR(200) NULL,
  branch VARCHAR(80) NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'pending',
  reply VARCHAR(500) NULL,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- v2.0: cooking hub (recipes, blog posts, comments, reader submissions). Seeded from data/recipes-seed.json on first run.
CREATE TABLE IF NOT EXISTS recipe_cats (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(60) NOT NULL UNIQUE,
  icon VARCHAR(8) NOT NULL DEFAULT '',
  sort_order INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS recipes (
  id INT AUTO_INCREMENT PRIMARY KEY,
  kind VARCHAR(10) NOT NULL DEFAULT 'recipe',
  slug VARCHAR(100) NOT NULL UNIQUE,
  title VARCHAR(160) NOT NULL,
  category VARCHAR(60) NOT NULL DEFAULT '',
  style VARCHAR(40) NOT NULL DEFAULT '',
  cuisine VARCHAR(40) NOT NULL DEFAULT '',
  difficulty VARCHAR(20) NOT NULL DEFAULT '',
  prep_min INT NOT NULL DEFAULT 0,
  cook_min INT NOT NULL DEFAULT 0,
  servings INT NOT NULL DEFAULT 0,
  summary VARCHAR(500) NOT NULL DEFAULT '',
  ingredients TEXT NULL,
  steps TEXT NULL,
  tips TEXT NULL,
  body MEDIUMTEXT NULL,
  tags VARCHAR(220) NOT NULL DEFAULT '',
  badge VARCHAR(40) NOT NULL DEFAULT '',
  image VARCHAR(300) NOT NULL DEFAULT '',
  featured TINYINT(1) NOT NULL DEFAULT 0,
  status VARCHAR(12) NOT NULL DEFAULT 'published',
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  KEY idx_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS recipe_comments (
  id INT AUTO_INCREMENT PRIMARY KEY,
  recipe_id INT NOT NULL,
  parent_id INT NOT NULL DEFAULT 0,
  name VARCHAR(60) NULL,
  comment VARCHAR(1300) NULL,
  rating TINYINT NOT NULL DEFAULT 0,
  status VARCHAR(12) NOT NULL DEFAULT 'pending',
  is_staff TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  KEY idx_recipe (recipe_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS recipe_submissions (
  id INT AUTO_INCREMENT PRIMARY KEY,
  kind VARCHAR(12) NOT NULL DEFAULT 'recipe',
  name VARCHAR(70) NULL,
  contact VARCHAR(90) NULL,
  title VARCHAR(160) NULL,
  message TEXT NULL,
  status VARCHAR(12) NOT NULL DEFAULT 'new',
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS site_settings (
  skey VARCHAR(40) PRIMARY KEY,
  svalue VARCHAR(200) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Azizo Kitchens (v3.0): partner home-kitchens marketplace.
CREATE TABLE IF NOT EXISTS kk_meta (skey VARCHAR(40) PRIMARY KEY, svalue MEDIUMTEXT NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS kk_dishes (
  id INT AUTO_INCREMENT PRIMARY KEY, slug VARCHAR(100) NOT NULL UNIQUE, name VARCHAR(100) NOT NULL, tradition VARCHAR(30) NOT NULL DEFAULT '', category VARCHAR(30) NOT NULL DEFAULT 'Combo',
  meal VARCHAR(8) NOT NULL DEFAULT 'both', price INT NOT NULL DEFAULT 0, serves INT NOT NULL DEFAULT 1, description VARCHAR(400) NOT NULL DEFAULT '', components TEXT, method TEXT, options TEXT,
  packaging VARCHAR(200) NOT NULL DEFAULT '', tips VARCHAR(300) NOT NULL DEFAULT '', image VARCHAR(300) NOT NULL DEFAULT '', active TINYINT(1) NOT NULL DEFAULT 1, sort_order INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS kk_kitchens (
  id INT AUTO_INCREMENT PRIMARY KEY, slug VARCHAR(80) NOT NULL UNIQUE, name VARCHAR(80) NOT NULL, cook_name VARCHAR(80), phone VARCHAR(20), email VARCHAR(100), password_hash VARCHAR(100),
  bio VARCHAR(600) NOT NULL DEFAULT '', specialities VARCHAR(200) NOT NULL DEFAULT '', experience VARCHAR(300) NOT NULL DEFAULT '', address VARCHAR(200) NOT NULL DEFAULT '',
  area_id VARCHAR(50) NOT NULL DEFAULT '', region VARCHAR(80) NOT NULL DEFAULT '', lat DOUBLE NULL, lng DOUBLE NULL, radius_km DOUBLE NOT NULL DEFAULT 4, capacity INT NOT NULL DEFAULT 10,
  prep_min INT NOT NULL DEFAULT 45, status VARCHAR(10) NOT NULL DEFAULT 'applied', commission_pct DOUBLE NULL, vetting TEXT, notes VARCHAR(1000) NOT NULL DEFAULT '', strikes INT NOT NULL DEFAULT 0,
  paused TINYINT(1) NOT NULL DEFAULT 0, docs MEDIUMTEXT, created_at DATETIME DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME DEFAULT CURRENT_TIMESTAMP, approved_at DATETIME NULL,
  INDEX (status), INDEX (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS kk_kitchen_dishes (kitchen_id INT NOT NULL, dish_id INT NOT NULL, available TINYINT(1) NOT NULL DEFAULT 1, PRIMARY KEY (kitchen_id, dish_id)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS kk_orders (
  id INT AUTO_INCREMENT PRIMARY KEY, kitchen_id INT NOT NULL, name VARCHAR(60), phone VARCHAR(20), address VARCHAR(200), area_id VARCHAR(50) NOT NULL DEFAULT '', lat DOUBLE, lng DOUBLE, distance_km DOUBLE NOT NULL DEFAULT 0,
  date VARCHAR(10), meal VARCHAR(8), notes VARCHAR(300) NOT NULL DEFAULT '', subtotal INT NOT NULL DEFAULT 0, delivery_fee INT NOT NULL DEFAULT 0, total INT NOT NULL DEFAULT 0, payment VARCHAR(8) NOT NULL DEFAULT 'cash',
  status VARCHAR(16) NOT NULL DEFAULT 'new', commission_pct DOUBLE NOT NULL DEFAULT 0, commission_amt INT NOT NULL DEFAULT 0, kitchen_amt INT NOT NULL DEFAULT 0, reason VARCHAR(200) NOT NULL DEFAULT '',
  rating INT NOT NULL DEFAULT 0, review VARCHAR(500) NOT NULL DEFAULT '', created_at DATETIME DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME DEFAULT CURRENT_TIMESTAMP, ready_at DATETIME NULL,
  INDEX (kitchen_id, date, meal), INDEX (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS kk_order_items (id INT AUTO_INCREMENT PRIMARY KEY, order_id INT NOT NULL, dish_id INT, name VARCHAR(100), qty INT, unit_price INT, options_text VARCHAR(300) NOT NULL DEFAULT '', line_total INT, INDEX (order_id)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS kk_payouts (id INT AUTO_INCREMENT PRIMARY KEY, kitchen_id INT NOT NULL, amount INT NOT NULL, reference VARCHAR(60) NOT NULL DEFAULT '', note VARCHAR(200) NOT NULL DEFAULT '', created_at DATETIME DEFAULT CURRENT_TIMESTAMP) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Azizo Kitchens v3.1: riders, promos, corporate accounts, meat supply, audit, outbox, demand log.
CREATE TABLE IF NOT EXISTS kk_riders (id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(60) NOT NULL, phone VARCHAR(20) NOT NULL, pin_hash VARCHAR(100) NOT NULL, active TINYINT(1) NOT NULL DEFAULT 1, created_at DATETIME DEFAULT CURRENT_TIMESTAMP) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS kk_promos (id INT AUTO_INCREMENT PRIMARY KEY, code VARCHAR(30) NOT NULL UNIQUE, kind VARCHAR(14) NOT NULL DEFAULT 'pct', value INT NOT NULL DEFAULT 0, min_order INT NOT NULL DEFAULT 0, max_uses INT NOT NULL DEFAULT 0, used INT NOT NULL DEFAULT 0, expires VARCHAR(10) NOT NULL DEFAULT '', active TINYINT(1) NOT NULL DEFAULT 1, note VARCHAR(120) NOT NULL DEFAULT '', created_at DATETIME DEFAULT CURRENT_TIMESTAMP) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS kk_corporate (id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(80) NOT NULL, code VARCHAR(30) NOT NULL UNIQUE, contact VARCHAR(60) NOT NULL DEFAULT '', phone VARCHAR(20) NOT NULL DEFAULT '', email VARCHAR(80) NOT NULL DEFAULT '', address VARCHAR(160) NOT NULL DEFAULT '', area_id VARCHAR(50) NOT NULL DEFAULT '', discount_pct DOUBLE NOT NULL DEFAULT 0, active TINYINT(1) NOT NULL DEFAULT 1, notes VARCHAR(200) NOT NULL DEFAULT '', created_at DATETIME DEFAULT CURRENT_TIMESTAMP) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS kk_supply (id INT AUTO_INCREMENT PRIMARY KEY, kitchen_id INT NOT NULL, items TEXT, note VARCHAR(200) NOT NULL DEFAULT '', total INT NOT NULL DEFAULT 0, status VARCHAR(12) NOT NULL DEFAULT 'requested', created_at DATETIME DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME DEFAULT CURRENT_TIMESTAMP) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS kk_audit (id INT AUTO_INCREMENT PRIMARY KEY, at DATETIME DEFAULT CURRENT_TIMESTAMP, actor VARCHAR(20) NOT NULL DEFAULT '', action VARCHAR(120) NOT NULL DEFAULT '', target VARCHAR(120) NOT NULL DEFAULT '', detail VARCHAR(500) NOT NULL DEFAULT '') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS kk_outbox (id INT AUTO_INCREMENT PRIMARY KEY, phone VARCHAR(20), kind VARCHAR(20) NOT NULL DEFAULT '', message TEXT, order_id INT NULL, status VARCHAR(10) NOT NULL DEFAULT 'pending', created_at DATETIME DEFAULT CURRENT_TIMESTAMP, sent_at DATETIME NULL, INDEX (status)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS kk_demand (date VARCHAR(10) NOT NULL, area_id VARCHAR(50) NOT NULL, region VARCHAR(80) NOT NULL DEFAULT '', name VARCHAR(80) NOT NULL DEFAULT '', n INT NOT NULL DEFAULT 0, PRIMARY KEY (date, area_id)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- v3.2: event enquiries from the Event Budget Planner
CREATE TABLE IF NOT EXISTS site_leads (
  id INT AUTO_INCREMENT PRIMARY KEY, created_at DATETIME DEFAULT CURRENT_TIMESTAMP, name VARCHAR(60) NOT NULL, phone VARCHAR(20) NOT NULL,
  event_date VARCHAR(10) NOT NULL DEFAULT '', guests INT NOT NULL DEFAULT 0, venue VARCHAR(120) NOT NULL DEFAULT '', note VARCHAR(400) NOT NULL DEFAULT '',
  estimate INT NOT NULL DEFAULT 0, mode VARCHAR(4) NOT NULL DEFAULT 'cost', items MEDIUMTEXT, status VARCHAR(12) NOT NULL DEFAULT 'new',
  admin_note VARCHAR(400) NOT NULL DEFAULT '', updated_at DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
